"""Rebuild the result tables from the per-case records under `results/`.

Nothing here is typed in by hand: every number in `docs/results/` comes out
of this module, so a table can always be traced back to the rows behind it.
"""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any

from .run import read_rows
from .stats import rate

Row = dict[str, Any]


def table(headers: list[str], rows: Iterable[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def group(rows: Iterable[Row], key: str | Callable[[Row], Any]) -> dict[Any, list[Row]]:
    pick = key if callable(key) else (lambda row: row[key])
    groups: dict[Any, list[Row]] = defaultdict(list)
    for row in rows:
        groups[pick(row)].append(row)
    return dict(groups)


def bench_report(rows: list[Row]) -> str:
    """Tables for the injection benchmark, one section per model."""
    parts = [
        "# Prompt-injection benchmark: results",
        "Generated by `cordon report` from `results/bench/`. Do not edit by hand.",
        "Rates are followed by a 95% interval. In the headline tables the interval comes "
        "from resampling whole tasks, because cases that share a task are not independent; "
        "in the breakdowns it is a Wilson interval over cases.",
    ]
    for model, model_rows in sorted(group(rows, "model").items()):
        parts.append(f"## {model}")
        parts.append(_headline(model_rows))
        baseline = [r for r in model_rows if r["defence"] == "none" and r["suite"] == "attacks"]
        if baseline:
            for column, title in [
                ("template", "By wording of the injection"),
                ("goal", "By what the attacker wants"),
                ("kind", "By where the text is planted"),
                ("task", "By task"),
            ]:
                parts.append(f"### No defence: {title.lower()}")
                parts.append(_breakdown(baseline, column))
    return "\n\n".join(parts) + "\n"


def _headline(rows: list[Row]) -> str:
    by_defence = group(rows, "defence")
    baseline = {r["id"]: r for r in by_defence.get("none", []) if r["suite"] == "attacks"}
    out = []
    order = sorted(by_defence, key=lambda name: (name != "none", name))
    for defence in order:
        clean = [r for r in by_defence[defence] if r["suite"] == "clean"]
        attacks = [r for r in by_defence[defence] if r["suite"] == "attacks"]
        same = [baseline[r["id"]] for r in attacks if r["id"] in baseline]
        out.append(
            [
                f"`{defence}`",
                f"{sum(r['utility'] for r in clean)}/{len(clean)}" if clean else "n/a",
                rate(attacks, "utility", "task"),
                rate(attacks, "attack", "task"),
                rate(same, "attack", "task") if defence != "none" else "",
                rate(attacks, "attempted", "task"),
                len(attacks),
            ]
        )
    return table(
        [
            "Defence",
            "Clean tasks solved",
            "Tasks solved under attack",
            "Attack succeeded",
            "No defence, same cases",
            "Attack attempted",
            "Cases",
        ],
        out,
    )


def _breakdown(rows: list[Row], column: str) -> str:
    groups = group(rows, column)
    ordered = sorted(groups, key=lambda name: -rate(groups[name], "attack").value)
    return table(
        [column.capitalize(), "Attack succeeded", "Task still solved", "Cases"],
        [
            [
                f"`{name}`",
                rate(groups[name], "attack"),
                rate(groups[name], "utility"),
                len(groups[name]),
            ]
            for name in ordered
        ],
    )


def fleet_report(rows: list[Row]) -> str:
    """Tables for the fleet control evaluation, one section per model."""
    parts = [
        "# Fleet control evaluation: results",
        "Generated by `cordon report` from `results/fleet/`. Do not edit by hand.",
        "`solo` is one agent with every tool and every policy. `fleet` is four agents with "
        "split privileges. `+shared` means an agent asked by a colleague is also shown the "
        "operator's original request. Intervals are 95%, from resampling whole tasks.",
    ]
    for model, model_rows in sorted(group(rows, "model").items()):
        parts.append(f"## {model}")
        conditions = group(model_rows, lambda r: (r["arm"], r["defence"]))
        out = []
        for (arm, defence), cond in sorted(conditions.items()):
            suites = group(cond, "suite")
            clean = suites.get("clean", [])
            injection = suites.get("injection", [])
            insider = suites.get("insider", [])
            out.append(
                [
                    f"`{arm}`",
                    f"`{defence}`",
                    f"{sum(r['utility'] for r in clean)}/{len(clean)}" if clean else "n/a",
                    rate(injection, "attack", "task") if injection else "n/a",
                    rate(injection, "attempted", "task") if injection else "n/a",
                    rate(injection, "utility", "task") if injection else "n/a",
                    len(injection),
                    rate(insider, "attack", "task") if insider else "n/a",
                    len(insider),
                ]
            )
        parts.append(
            table(
                [
                    "Arm",
                    "Defence",
                    "Clean jobs done",
                    "Injection succeeded",
                    "Injection acted on",
                    "Job done under injection",
                    "Cases",
                    "Insider succeeded",
                    "Cases",
                ],
                out,
            )
        )
        undefended = [r for r in model_rows if r["defence"] == "none" and r["suite"] == "injection"]
        if undefended:
            parts.append("### Injection, no defence: by what the attacker wants")
            parts.append(_by_arm(undefended, "goal"))
            parts.append("### How an injection travels through the fleet")
            parts.append(_propagation(undefended))
    return "\n\n".join(parts) + "\n"


def _by_arm(rows: list[Row], column: str) -> str:
    arms = sorted(group(rows, "arm"))
    out = []
    for name, cell in sorted(group(rows, column).items()):
        by_arm = group(cell, "arm")
        out.append([f"`{name}`"] + [rate(by_arm.get(arm, []), "attack") for arm in arms])
    return table([column.capitalize()] + [f"`{arm}`" for arm in arms], out)


def _propagation(rows: list[Row]) -> str:
    out = []
    for arm, cell in sorted(group(rows, "arm").items()):
        if arm.startswith("solo"):
            continue
        relayed = [r for r in cell if r["relayed"]]
        out.append(
            [
                f"`{arm}`",
                rate(cell, "relayed"),
                rate(relayed, "attack"),
                rate([r for r in cell if not r["relayed"]], "attack"),
            ]
        )
    return table(
        [
            "Arm",
            "First agent passed the attacker's request on",
            "Attack succeeded, given it was passed on",
            "Attack succeeded without being passed on",
        ],
        out,
    )


def monitor_report(sets: dict[str, tuple[dict[str, int], list[Row]]]) -> str:
    """Tables for the monitors: one section per set of recorded runs."""
    from .monitor import auroc, operating_points

    parts = [
        "# Monitors: results",
        "Generated by `cordon report` from `results/monitor/`. Do not edit by hand.",
        "Each monitor scores every change and every request between agents in the recorded "
        "runs, none of which had a defence. The audit rate is the share of events from "
        "honest runs at or above the threshold: the work a person would have to do. "
        "`Caught` is the share of successful attacks with a flagged event that served the "
        "attack. `Uncaught` is the share of all attack runs that succeeded with nothing "
        "flagged.",
    ]
    for name, (counts, rows) in sorted(sets.items()):
        parts.append(f"## {name}")
        parts.append(
            f"{counts['honest']} honest runs and {counts['attacked']} attack runs, of which "
            f"{counts['succeeded']} succeeded."
        )
        monitors = group(rows, "monitor")
        parts.append(
            table(
                ["Monitor", "AUROC, attack-serving against honest events", "Events scored"],
                [[f"`{m}`", f"{auroc(r):.2f}", len(r)] for m, r in sorted(monitors.items())],
            )
        )
        for monitor, scored in sorted(monitors.items()):
            parts.append(f"### `{monitor}`")
            points = operating_points(scored, counts["attacked"])
            parts.append(
                table(
                    ["Flag at score", "Audit rate", "Caught", "Uncaught"],
                    [
                        [
                            f">= {p.threshold:.0f}" if p.threshold <= 9 else "never",
                            f"{100 * p.audit_rate:.0f}%",
                            f"{100 * p.caught:.0f}%",
                            f"{100 * p.uncaught_success:.1f}%",
                        ]
                        for p in points
                    ],
                )
            )
    return "\n\n".join(parts) + "\n"


def interp_report(results: dict[str, dict[str, Any]]) -> str:
    """Tables for the probing track, one section per model."""
    parts = [
        "# Probing: results",
        "Generated by `cordon report` from `results/interp/`. Do not edit by hand.",
        "Activations are read at the last token of the prompt, at the moment the agent has "
        "read planted text and is about to choose its next move. Every score is on groups "
        "held out of training. Intervals are 95% bootstrap intervals over examples.",
    ]
    questions = {
        "injected": "Is the planted text an attack or a harmless note?",
        "attempted": "Among attacks, will the agent act on this one?",
    }
    for _, result in sorted(results.items()):
        counts = result["counts"]
        parts.append(f"## {result['model']}")
        parts.append(
            f"{counts['examples']} decision points: {counts['injected']} with an attack "
            f"planted and {counts['examples'] - counts['injected']} with a harmless note. "
            f"The agent acted on {counts['attempted']} of the attacks and "
            f"{counts['succeeded']} succeeded. {result['never_read']} recorded runs are left "
            f"out because the agent never read the planted text. The model has "
            f"{result['layers']} layers of width {result['width']}."
        )
        for label, question in questions.items():
            chosen = result["compare"][label]
            parts.append(f"### {question}")
            sweep = result["sweep"][label]
            best = sorted(sweep, key=lambda row: -row["auroc"])[:3]
            parts.append(
                f"Layer {chosen['layer']} is used below. It was picked as the best layer on "
                "held-out templates, so the held-out-template row is optimistic; the other "
                "two rows are not affected by that choice in the same way. Best three layers "
                "on held-out templates: "
                + ", ".join(f"{row['layer']} ({row['auroc']:.2f})" for row in best)
                + "."
            )
            methods = list(next(iter(chosen["splits"].values())))
            parts.append(
                table(
                    ["Held out", *methods],
                    [
                        [f"one {split}"]
                        + [
                            f"{cell['auroc']:.2f} ({cell['low']:.2f}-{cell['high']:.2f})"
                            for cell in (chosen["splits"][split][m] for m in methods)
                        ]
                        for split in chosen["splits"]
                    ],
                )
            )
        warning = result["early_warning"]
        parts.append("### The attack probe as an early warning")
        parts.append(
            f"Scores are from probes that never saw the example's template, at layer "
            f"{warning['layer']}. The threshold is set on harmless notes. "
            f"{warning['succeeded']} attacks went on to succeed."
        )
        parts.append(
            table(
                ["Harmless notes flagged", "Attacks flagged", "Attacks that succeeded, flagged"],
                [
                    [
                        f"{100 * p['false_alarm_rate']:.0f}%",
                        f"{100 * p['attacks_flagged']:.0f}%",
                        f"{100 * p['successful_attacks_flagged']:.0f}%",
                    ]
                    for p in warning["points"]
                ],
            )
        )
    return "\n\n".join(parts) + "\n"


def write_reports(results: Path, out: Path) -> list[Path]:
    import json

    out.mkdir(parents=True, exist_ok=True)
    written = []

    def write(name: str, text: str) -> None:
        path = out / name
        path.write_text(text)
        written.append(path)

    if (results / "bench").exists():
        write("bench.md", bench_report(read_rows(results / "bench")))
    if (results / "fleet").exists():
        write("fleet.md", fleet_report(read_rows(results / "fleet")))
    if (results / "monitor").exists():
        sets = {}
        for directory in sorted(p for p in (results / "monitor").iterdir() if p.is_dir()):
            counts = json.loads((directory / "counts.json").read_text())
            sets[directory.name] = (counts, read_rows(directory))
        write("monitor.md", monitor_report(sets))
    if (results / "interp").exists():
        probes = {
            path.parent.name: json.loads(path.read_text())
            for path in sorted((results / "interp").glob("*/probes.json"))
        }
        if probes:
            write("interp.md", interp_report(probes))
    return written
